const REGIONAL_A = 0x1f1e6;
let regions: Intl.DisplayNames | null = null;

/*
 * В наборе эмодзи названия русские, а шорткоды — английские (`heart_eyes`): из них и подпись. Флаг —
 * пара региональных букв, шорткод у него — код страны (`ua`), поэтому название страны берёт Intl.
 */
function emojiName(emoji: EmojiItem): string {
  const points = Array.from(emoji.char, (char) => char.codePointAt(0) ?? 0);
  const isFlag =
    points.length === 2 && points.every((point) => point >= REGIONAL_A && point < REGIONAL_A + 26);

  if (isFlag) {
    const code = String.fromCharCode(...points.map((point) => point - REGIONAL_A + 65));

    try {
      regions ??= new Intl.DisplayNames(['en'], { type: 'region' });

      return `flag: ${regions.of(code) ?? code}`;
    } catch {
      return `flag: ${code}`;
    }
  }

  return emoji.shortcode.replaceAll('_', ' ');
}

